#!/usr/bin/env python3
"""Generate the offline policy from the published website's HTML source."""
import argparse
import json
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'assets/legal/privacy-policy.json'
DART_OUTPUT = ROOT / 'lib/screens/settings/privacy_policy_content.g.dart'


class PolicyParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.in_main = False
        self.tag = None
        self.parts = []
        self.link = None
        self.introduction = []
        self.sections = []

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        if tag == 'main':
            self.in_main = True
        elif self.in_main and tag in ('h2', 'p') and not (tag == 'p' and attributes.get('class') == 'eyebrow'):
            self.tag = tag
            self.parts = []
        elif self.tag and tag == 'a':
            self.link = attributes.get('href')

    def handle_data(self, data):
        if self.tag:
            self.parts.append(data)

    def handle_endtag(self, tag):
        if tag == 'a' and self.tag:
            if self.link == '/delete-data.html':
                self.parts.append(' (https://luroka.app/delete-data.html)')
            self.link = None
        elif tag == self.tag:
            text = ' '.join(''.join(self.parts).split())
            if tag == 'h2':
                self.sections.append({'heading': text, 'paragraphs': []})
            elif self.sections:
                self.sections[-1]['paragraphs'].append(text)
            else:
                self.introduction.append(text)
            self.tag = None
        elif tag == 'main':
            self.in_main = False


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True, help='Path to the current privacy.html')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    policy = PolicyParser()
    policy.feed(args.source.read_text(encoding='utf-8'))
    if len(policy.introduction) != 2 or len(policy.sections) != 10:
        raise SystemExit('Unexpected privacy policy layout; review the source before updating the app')
    data = {'introduction': policy.introduction, 'sections': policy.sections}
    output = (json.dumps(data, ensure_ascii=False, indent=2) + '\n').encode('utf-8')
    def dart_string(value):
        return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
    lines = [
        '// Generated by scripts/codegen/generate_privacy_policy.py. Do not edit.',
        'const privacyPolicyIntroduction = <String>[',
        *(f'  {dart_string(text)},' for text in policy.introduction),
        '];',
        'const privacyPolicySections = <({String heading, List<String> paragraphs})>[',
    ]
    for section in policy.sections:
        lines.append(f'  (heading: {dart_string(section["heading"])}, paragraphs: <String>[')
        lines.extend(f'    {dart_string(text)},' for text in section['paragraphs'])
        lines.append('  ]),')
    lines.append('];')
    dart_output = ('\n'.join(lines) + '\n').encode('utf-8')
    if args.check:
        if OUTPUT.read_bytes() != output:
            raise SystemExit('The bundled privacy policy differs from the website source')
        if DART_OUTPUT.read_bytes() != dart_output:
            raise SystemExit('The generated Dart privacy policy differs from the website source')
    else:
        OUTPUT.write_bytes(output)
        DART_OUTPUT.write_bytes(dart_output)
    print(f'Privacy policy verified: {len(policy.sections)} sections')


if __name__ == '__main__':
    main()
